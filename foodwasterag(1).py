from sentence_transformers import SentenceTransformer
import faiss
import numpy as np

docs = [
    "Red Cross accepts surplus cooked food within 2 hours of preparation.",
    "Feeding India collects excess food from restaurants and hotels in major Indian cities.",
    "Food Safety rules: cooked food should be stored below 5°C if not distributed immediately.",
    "NGOs prefer packaged food over loose food for hygiene reasons.",
    "Surplus food should be distributed within 4-6 hours to avoid waste."
]

model_embed = SentenceTransformer("all-MiniLM-L6-v2")

embeddings = model_embed.encode(docs)

dimension = embeddings.shape[1]

index = faiss.IndexFlatL2(dimension)
index.add(np.array(embeddings))

def retrieve(query):
    q_emb = model_embed.encode([query])
    D, I = index.search(np.array(q_emb), k=2)

    results = [docs[i] for i in I[0]]
    return results

query = "Where can surplus food be donated?"
print(retrieve(query))

predicted_waste = 120

query = "Where should surplus food be donated?"
suggestions = retrieve(query)

print(suggestions)

print(" FOOD WASTE ANALYSIS REPORT ")
print(f"Predicted Waste: {predicted_waste} kg\n")

print(" Redistribution Suggestions:")
for s in suggestions:
    print("-", s)

print("\n Recommendation: Distribute within 4–6 hours to avoid spoilage.")